#!/usr/bin/env python3
"""Truthful pre-certification summary. This draft is replaced after actual certification."""
import json,os,pathlib
root=pathlib.Path(os.environ['TILEO_EVIDENCE'])
load=lambda name:json.loads((root/name).read_text())
c=load('candidate.json');n=load('tests/integration-test-results.json');b=load('tests/browser/execution.json');s=load('compliance/source-verification.json');d=load('tests/distribution/execution.json')
assert n['passed'] is True and n['exit_code']==0 and b['exit_code']==0 and b['failed']==0
assert d['status']=='VERIFIED' and d['exit_code']==0 and d['image_id']==c['image_id']
assert s['status']=='VERIFIED' and s['image']['id']==c['image_id']
assert all(x['image_id']==c['image_id'] for x in [n,b])
p=root/'release/RELEASE_CLOSURE_REPORT.md';assert not p.exists(),'Refusing to overwrite an existing closure report'
p.write_text(f'''# TileO 0.1.0 — preliminary engineering summary

Status: PENDING_TECHNICAL_CERTIFICATION — not technical eligibility or human approval.

Commit: `{c['commit']}`
Image ID: `{c['image_id']}`
Candidate: `{c['candidate_id']}`

Observed integration: exit {n['exit_code']}, summary {json.dumps(n['tap_summary'])}.
Observed browser: exit {b['exit_code']}, expected {b['expected']}, failed {b['failed']}, skipped {b['skipped']}; scope approval remains pending.
Observed source verification: {s['status']}.
Observed public Compose API/worker smoke: {d['status']}, exit {d['exit_code']}.

Negative controls and technical certification are not yet established by this draft. Engineering, Legal/IP and Release Steward approvals remain PENDING. No publication is authorized.

This truthful preliminary report exists for the pre-negative required-path check. Replace it with create-release-closure-report.js only after actual technical eligibility; then finalize provenance again and freeze the manifest. No PASS is generated by this helper.
''')
print('Pre-certification summary written; all approvals still PENDING')
