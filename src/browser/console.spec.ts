import { test, expect } from '@playwright/test';
test('English console uploads, converts with Tippecanoe, previews and rejects invalid CRS', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#connection')).toContainText('Worker connected', { timeout: 30000 });
  await expect(page.locator('#vector-options-group')).toBeHidden();
  await expect(page.locator('#raster-options-group')).toBeHidden();
  // Inspection is serialized server-side. Finish the deliberately invalid TIFF
  // before selecting the next dataset, rather than aborting its browser request
  // while GDAL still holds the server upload slot.
  const invalidInspection = page.waitForResponse(response =>
    response.request().method() === 'POST' && response.url().includes('/api/inspect?filename=image.tif'));
  await page.locator('#file').setInputFiles({ name: 'image.tif', mimeType: 'image/tiff', buffer: Buffer.from('test') });
  await expect(page.locator('#file-info')).toContainText('image.tif');
  await expect(page.locator('#vector-options-group')).toBeHidden();
  await expect(page.locator('#raster-options-group')).toBeVisible();
  expect((await invalidInspection).ok()).toBeFalsy();
  await expect(page.locator('#upload-status')).toBeHidden();
  await page.locator('#clear-file').click();
  await expect(page.locator('#file-info')).toBeHidden();
  await expect(page.locator('#raster-options-group')).toBeHidden();
  await expect(page.locator('#file')).toHaveValue('');
  const file = { name: `browser-${Date.now()}.geojson`, mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ type: 'FeatureCollection', features: [{ type: 'Feature', properties: { name: 'Test point' }, geometry: { type: 'Point', coordinates: [119.4,-5.15] } }] })) };
  const vectorInspection = page.waitForResponse(response =>
    response.request().method() === 'POST' && response.url().includes(`/api/inspect?filename=${file.name}`));
  await page.locator('#file').setInputFiles(file);
  expect((await vectorInspection).ok()).toBeTruthy();
  await expect(page.getByRole('button', { name: 'Create tile job' })).toBeEnabled();
  await expect(page.locator('#vector-options-group')).toBeVisible();
  await expect(page.locator('#raster-options-group')).toBeHidden();
  await page.locator('#max-zoom').fill('4');
  await page.getByRole('button', { name: 'Create tile job' }).click();
  const job = page.locator('article').filter({ hasText: file.name });
  await expect(job.locator('.badge')).toHaveText('SUCCEEDED', { timeout: 90000 });
  await page.reload();
  await expect(job.locator('.badge')).toHaveText('SUCCEEDED');
  await job.getByRole('button', { name: 'Add to map', exact: true }).click();
  await expect(page.locator('#map canvas')).toBeVisible();
  await expect(page.locator('#preview-name')).toHaveText(file.name);
  const secondFile = { ...file, name: `browser-layer-${Date.now()}.geojson` };
  await page.locator('#file').setInputFiles(secondFile);
  await page.locator('#max-zoom').fill('4');
  await page.getByRole('button', { name: 'Create tile job' }).click();
  const secondJob = page.locator('article').filter({ hasText: secondFile.name });
  await expect(secondJob.locator('.badge')).toHaveText('SUCCEEDED', { timeout: 90000 });
  await secondJob.getByRole('button', { name: 'Add to map', exact: true }).click();
  await expect(page.locator('#map-layers .map-layer-row')).toHaveCount(2);
  await expect(page.locator('#preview-name')).toHaveText('2 results on map');
  await expect(job.getByRole('button', { name: 'Zoom to', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Collapse layer panel' }).click();
  await expect(page.locator('#map-layers-panel')).toHaveClass(/is-collapsed/);
  await expect(page.locator('#map-layers')).toBeHidden();
  await page.getByRole('button', { name: 'Expand layer panel' }).click();
  const firstLayerRow = page.locator('.map-layer-row').filter({ hasText: file.name });
  await firstLayerRow.getByRole('button', { name: `Hide ${file.name}` }).click();
  await expect(firstLayerRow).toHaveClass(/is-hidden/);
  await firstLayerRow.getByRole('button', { name: `Show ${file.name}` }).click();
  await firstLayerRow.locator('input[type=range]').fill('55');
  await expect(firstLayerRow.locator('input[type=range]')).toHaveValue('55');
  await secondJob.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(page.locator('#map-layers .map-layer-row')).toHaveCount(1);
  await expect(page.locator('#preview-name')).toHaveText(file.name);
  await job.getByRole('button', { name: 'More actions' }).click();
  await job.getByRole('menuitem', { name: 'Benchmark' }).click();
  await expect(page.locator('#benchmark-dialog')).toBeVisible();
  await expect(page.locator('.benchmark-verdicts .verdict').first()).toBeVisible();
  await page.locator('#close-benchmark').click();
  await job.getByRole('button', { name: 'More actions' }).click();
  const compareItem = job.getByRole('menuitem', { name: 'Compare source' });
  if (await compareItem.count() > 0) {
    await compareItem.click();
    await expect(page.locator('.compare-control')).toHaveAttribute('data-ready', 'true', { timeout: 30000 });
    await expect(page.locator('.compare-label-source')).toContainText('1 feature');
    await expect(page.locator('.compare-source-map canvas')).toBeVisible();
    await page.locator('.compare-control').getByRole('button', { name: 'Close', exact: true }).click();
  }
  const download = await page.request.get(await job.getByRole('link', { name: 'Download MBTiles' }).getAttribute('href') ?? '');
  expect(download.ok()).toBeTruthy();
  expect((await download.body()).subarray(0,15).toString()).toBe('SQLite format 3');
  await page.screenshot({ path: 'test-results/console-desktop.png', fullPage: true });
  await page.locator('#file').setInputFiles({ ...file, name: `invalid-${file.name}` });
  await page.locator('summary').filter({ hasText: 'Source options' }).click();
  await page.locator('#source-crs').fill('EPSG:8611');
  await page.getByRole('button', { name: 'Create tile job' }).click();
  await expect(page.locator('article').filter({ hasText: `invalid-${file.name}` }).locator('.error')).toContainText('INVALID_CRS', { timeout: 30000 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/console-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
