import { test, expect } from '@playwright/test';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

test('DSM/DTM inspection, COG and terrain jobs, preview, downloads and deletion', async ({ page }) => {
  const dir = await mkdtemp(join(tmpdir(), 'tileo-elevation-browser-'));
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const encoderUrl = new URL('../../dist/elevation.js', import.meta.url).href;
  const { terrainPng } = await import(encoderUrl);
  const basemap = terrainPng(new Float64Array(256 * 256).fill(-10000 + 0xeceff2 * 0.1));
  // Keep this check independent of an external basemap service.
  await page.route('**/api/basemap/osm/**', route => route.fulfill({ contentType: 'image/png', body: basemap }));
  try {
    const runnerUrl = new URL('../../dist/process.js', import.meta.url).href;
    const { run } = await import(runnerUrl);
    const ascii = join(dir, 'dtm.asc'), tif = join(dir, 'dtm.tif');
    await writeFile(ascii, 'ncols 8\nnrows 8\nxllcorner 119.35\nyllcorner -5.2\ncellsize 0.01\nNODATA_value -9999\n' + Array.from({ length: 8 }, (_, y) => Array.from({ length: 8 }, (_, x) => x === 0 && y === 0 ? -9999 : 100).join(' ')).join('\n'));
    await run('gdal_translate', ['-a_srs', 'EPSG:4326', '-ot', 'Float32', ascii, tif]);
    const file = { name: `dtm-browser-${Date.now()}.tif`, mimeType: 'image/tiff', buffer: await readFile(tif) };
    await page.goto('/');
    await expect(page.locator('#connection')).toContainText('Worker connected', { timeout: 30000 });
    await page.locator('#file').setInputFiles(file);
    await expect(page.locator('#elevation-options-group')).toBeVisible();
    await expect(page.locator('#submit')).toBeEnabled();
    await expect(page.locator('#raster-purpose')).toHaveValue('elevation');
    await expect(page.locator('#zoom-options-group')).toBeHidden();
    await expect(page.locator('#raster-options-group')).toBeHidden();
    await expect(page.locator('#source-crs')).toHaveValue('');
    await page.locator('#elevation-kind').selectOption('dtm');
    await page.route('**/api/jobs?**', route => route.fulfill({ status: 400, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Submission failed; retry.' } }) }));
    await page.locator('#submit').click();
    await expect(page.locator('#notice')).toContainText('Submission failed');
    await expect(page.locator('#file-info')).toContainText(file.name);
    await expect(page.locator('#elevation-kind')).toHaveValue('dtm');
    await page.unroute('**/api/jobs?**');
    await page.locator('#submit').click();
    await expect(page.locator('#file')).toHaveValue('');
    await expect(page.locator('#file-info')).toBeHidden();
    await expect(page.locator('#elevation-options-group')).toBeHidden();
    await expect(page.locator('#source-options-group')).toBeHidden();
    await expect(page.locator('#tip-box')).toBeHidden();
    const cogJob = page.locator('article').filter({ hasText: file.name });
    await expect(cogJob.locator('.badge')).toHaveText('SUCCEEDED', { timeout: 60000 });
    const download = await page.request.get(await cogJob.getByRole('link', { name: 'Download COG' }).getAttribute('href') ?? '');
    expect(download.status()).toBe(200); expect(download.headers()['content-type']).toBe('image/tiff');
    const bytes = await download.body(); expect(['II', 'MM']).toContain(bytes.subarray(0, 2).toString());
    const cogRange = page.waitForResponse(response => /\/api\/jobs\/[^/]+\/cog$/.test(response.url()) && response.status() === 206);
    await cogJob.getByRole('button', { name: 'Open preview', exact: true }).click();
    await cogRange;
    await expect(page.locator('#loaded-data-info')).toContainText('COG elevation');
    await expect(page.locator('#map canvas')).toBeVisible();
    await expect(page.locator('#notice')).not.toContainText('COG preview:', { timeout: 10000 });
    await page.screenshot({ path: 'test-results/cog-elevation-preview.png', fullPage: true });
    await cogJob.getByRole('button', { name: 'More actions' }).click();
    await cogJob.getByRole('menuitem', { name: 'Compare source' }).click();
    await expect(page.locator('.compare-control')).toHaveAttribute('data-ready', 'true', { timeout: 30000 });
    await expect(page.locator('.compare-label-source')).toContainText('Original source');
    await expect(page.locator('.compare-label-result')).toContainText('Converted result');
    await expect(page.locator('.compare-source-map canvas')).toBeVisible();
    await page.getByRole('button', { name: 'Source only', exact: true }).click();
    await expect(page.locator('.compare-label-result')).toBeHidden();
    await page.getByRole('button', { name: 'Result only', exact: true }).click();
    await expect(page.locator('.compare-label-source')).toBeHidden();
    await page.getByRole('button', { name: '50 : 50', exact: true }).click();
    await expect(page.locator('.compare-source-map')).toHaveCSS('clip-path', 'inset(0px 50% 0px 0px)');
    const viewport = page.viewportSize()!;
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await page.setViewportSize(viewport);
    await page.screenshot({ path: 'test-results/compare-elevation.png', fullPage: true });
    await page.locator('.compare-control').getByRole('button', { name: 'Close', exact: true }).click();
    await expect(page.locator('.compare-control')).toHaveCount(0);
    await expect(page.locator('#map canvas')).toHaveCount(1);
    await expect(page.locator('#elevation-options-group')).toBeHidden();
    const terrainFile = { ...file, name: `terrain-${file.name}` };
    await page.locator('#file').setInputFiles(terrainFile);
    await expect(page.locator('#submit')).toBeEnabled();
    await page.locator('#elevation-output').selectOption('terrain-rgb');
    await expect(page.locator('#zoom-options-group')).toBeVisible();
    await page.locator('#elevation-unit').selectOption('m');
    await page.locator('#height-reference').selectOption('orthometric');
    await page.locator('#terrain-nodata-height').fill('0');
    await page.locator('#min-zoom').fill('6'); await page.locator('#max-zoom').fill('6');
    await page.locator('#submit').click();
    await expect(page.locator('#file')).toHaveValue('');
    await expect(page.locator('#terrain-nodata-height')).toHaveValue('');
    await expect(page.locator('#height-reference')).toHaveValue('unknown');
    await expect(page.locator('#zoom-options-group')).toBeHidden();
    const terrainJob = page.locator('article').filter({ hasText: terrainFile.name });
    await expect(terrainJob.locator('.badge')).toHaveText('SUCCEEDED', { timeout: 60000 });
    const zip = await page.request.get(await terrainJob.getByRole('link', { name: 'Download elevation' }).getAttribute('href') ?? '');
    expect(zip.status()).toBe(200); expect((await zip.body()).subarray(0, 2).toString()).toBe('PK');
    const artifactUrl = (await terrainJob.getByRole('link', { name: 'Download elevation' }).getAttribute('href'))!;
    const tilejson = await page.request.get(artifactUrl.replace('/download', '/tilejson'));
    expect(tilejson.status()).toBe(200); expect((await tilejson.json()).encoding).toBe('mapbox');
    const individual = await page.request.get(`${artifactUrl}?file=terrain`);
    expect(individual.status()).toBe(200); expect((await individual.body()).subarray(0, 15).toString()).toBe('SQLite format 3');
    const tileLoaded = page.waitForResponse(response => /\/api\/jobs\/[^/]+\/tiles\//.test(response.url()) && response.status() === 200);
    await terrainJob.getByRole('button', { name: 'Open preview', exact: true }).click();
    await expect(page.locator('#loaded-data-info')).toContainText('Terrain-RGB');
    await tileLoaded;
    await expect(page.locator('#notice')).toContainText('Missing terrain pixels');
    await page.screenshot({ path: 'test-results/elevation-preview.png', fullPage: true });
    page.once('dialog', dialog => dialog.accept());
    await terrainJob.getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(terrainJob).toHaveCount(0);
    await expect(page.locator('#preview-name')).toContainText('Basemap only');
    const terrariumFile = { ...file, name: `terrarium-${file.name}` };
    await page.locator('#file').setInputFiles(terrariumFile);
    await expect(page.locator('#submit')).toBeEnabled();
    await page.locator('#elevation-output').selectOption('terrarium');
    await page.locator('#export-pmtiles').selectOption('yes');
    await page.locator('#elevation-unit').selectOption('m');
    await page.locator('#height-reference').selectOption('orthometric');
    await page.locator('#terrain-nodata-height').fill('-20000');
    await page.locator('#min-zoom').fill('6'); await page.locator('#max-zoom').fill('6');
    await page.locator('#submit').click();
    const terrariumJob = page.locator('article').filter({ hasText: terrariumFile.name });
    await expect(terrariumJob.locator('.badge')).toHaveText('SUCCEEDED', { timeout: 60000 });
    const terrariumUrl = (await terrariumJob.getByRole('link', { name: 'Download elevation' }).getAttribute('href'))!.replace('/download', '');
    const terrainMetadata = await (await page.request.get(`${terrariumUrl}/tilejson`)).json();
    expect(terrainMetadata.encoding).toBe('terrarium');
    const pmtiles = await page.request.get(`${terrariumUrl}/download?file=pmtiles`);
    expect(pmtiles.status()).toBe(200); expect((await pmtiles.body()).subarray(0, 7).toString()).toBe('PMTiles');
    const wmts = await page.request.get(`${terrariumUrl}/wmts?SERVICE=WMTS&REQUEST=GetCapabilities`);
    expect(wmts.status()).toBe(200); expect(await wmts.text()).toContain('WebMercatorQuad');
    const terrariumTile = page.waitForResponse(response => /\/api\/jobs\/[^/]+\/tiles\//.test(response.url()) && response.status() === 200);
    await terrariumJob.getByRole('button', { name: 'Open preview', exact: true }).click();
    await terrariumTile; await expect(page.locator('#loaded-data-info')).toContainText('Terrarium');
    page.once('dialog', dialog => dialog.accept());
    await terrariumJob.getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(terrariumJob).toHaveCount(0);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    expect(errors).toEqual([]);
  } finally { await rm(dir, { recursive: true, force: true }); }
});
